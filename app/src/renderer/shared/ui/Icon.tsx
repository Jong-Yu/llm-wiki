export type IconName = keyof typeof icons;
type IconProps = { name: IconName; size?: number; className?: string };

/** 표준 Lucide 아이콘의 크기와 선 두께를 맞춥니다. 접근성 이름은 부모 컨트롤이 소유합니다. */
export function Icon({ name, size = 16, className }: IconProps): JSX.Element {
  const Glyph = icons[name];
  return (
    <Glyph
      aria-hidden="true"
      focusable="false"
      size={size}
      strokeWidth={1.75}
      className={className}
    />
  );
}
